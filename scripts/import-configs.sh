#!/usr/bin/env bash
# import-configs.sh - copy your existing ~/.config folders into configs/.config (repository staging).
#
# It copies ONLY the folders listed in IMPORT_DIRS, keeps the hierarchy and file contents untouched,
# and leaves machine-specific / private files out (see EXCLUDES and docs/configuracao.md).
# Nothing is ever deleted from your home directory.
#
# Usage: import-configs.sh [--from DIR] [--with-local-bin] [--dry-run] [--yes] [--lang en|pt_BR] [--no-color]
#   --from DIR         source of the .config folders (default: ~/.config)
#   --with-local-bin   also copy ~/.local/bin/wallpaper-menu (used by the SUPER+D binding)
# shellcheck disable=SC2034  # option/config variables are consumed by the sourced libraries
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MONOLITH_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
export MONOLITH_ROOT
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=lib/i18n.sh
source "$SCRIPT_DIR/lib/i18n.sh"
# shellcheck source=lib/messages.sh
source "$SCRIPT_DIR/lib/messages.sh"
# shellcheck source=lib/ui.sh
source "$SCRIPT_DIR/lib/ui.sh"

IMPORT_DIRS=(hypr quickshell fish ghostty fastfetch btop swaync nvim micro gtk-3.0 gtk-4.0 nwg-look wal wpg)
LOCAL_BIN_FILES=(wallpaper-menu)
# tar --exclude patterns, matched against paths relative to ~/.config
EXCLUDES=(
    'micro/backups'            # editor backups of arbitrary files (may contain secrets)
    'fish/fish_variables'      # universal variables: machine paths, history of PATH changes
    'fish/conf.d/*.env.fish'   # generated by third-party installers (atuin, uv, ...)
    'wpg/schemes'              # generated colour schemes (contain absolute paths)
    'wpg/sequences'            # generated terminal escape sequences
    'wpg/samples'              # generated previews
    'wal/colors*'              # pywal cache
    'wal/sequences'            # pywal cache
    '*.bak' '*~' '*.swp' '*.tmp' '*.log' '__pycache__' '.git' '.DS_Store'
)

SRC="${HOME}/.config" WITH_BIN=0 DRY=0 OPT_YES=0

usage() { sed -n '2,13p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while (( $# )); do
    case $1 in
        --from) SRC=${2:?--from needs a directory}; shift 2 ;;
        --from=*) SRC=${1#*=}; shift ;;
        --with-local-bin) WITH_BIN=1; shift ;;
        --dry-run | -n) DRY=1; shift ;;
        --yes | -y) OPT_YES=1; shift ;;
        --lang) MONOLITH_LANG=$(normalize_lang "${2:?}") || MONOLITH_LANG=en; shift 2 ;;
        --lang=*) MONOLITH_LANG=$(normalize_lang "${1#*=}") || MONOLITH_LANG=en; shift ;;
        --no-color) OPT_NO_COLOR=1; shift ;;
        -h | --help) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage >&2; exit 1 ;;
    esac
done
export MONOLITH_LANG
ui_init
init_logging import

[[ -d $SRC ]] || { ui_err "$(t import.no_source "$SRC")"; exit 1; }
DEST="$MONOLITH_CONFIGS_DIR/.config"
mkdir -p "$DEST"

ui_info "$(t import.start "$SRC" "$(short_path "$DEST")")"
if (( ! DRY )) && ! ui_confirm "$(t import.confirm)" y; then
    ui_warn "$(t common.aborted)"
    exit 3
fi

tar_excludes=()
for pat in "${EXCLUDES[@]}"; do tar_excludes+=(--exclude="$pat"); done

copied=0 skipped=0
for d in "${IMPORT_DIRS[@]}"; do
    if [[ ! -d $SRC/$d ]]; then
        ui_dim "$(t import.missing "$d")"
        skipped=$(( skipped + 1 ))
        continue
    fi
    n=$(cd "$SRC" && tar -cf - "${tar_excludes[@]}" "$d" 2>/dev/null | tar -tf - | grep -vc '/$' || true)
    if (( DRY )); then
        ui_info "$(t import.would_copy "$d" "$n")"
    else
        (cd "$SRC" && tar -cf - "${tar_excludes[@]}" "$d") | tar -xf - -C "$DEST"
        log INFO "imported $d ($n files)"
        ui_ok "$(t import.copied "$d" "$n")"
    fi
    copied=$(( copied + 1 ))
done

if (( WITH_BIN )); then
    mkdir -p "$MONOLITH_CONFIGS_DIR/.local/bin"
    for f in "${LOCAL_BIN_FILES[@]}"; do
        if [[ -f $HOME/.local/bin/$f ]]; then
            (( DRY )) || cp -p -- "$HOME/.local/bin/$f" "$MONOLITH_CONFIGS_DIR/.local/bin/$f"
            ui_ok "$(t import.local_bin "$f")"
        else
            ui_dim "$(t import.missing ".local/bin/$f")"
        fi
    done
fi

# tell the user what was deliberately left out
left=0
for d in "${IMPORT_DIRS[@]}"; do
    [[ -d $SRC/$d ]] || continue
    for pat in "${EXCLUDES[@]}"; do
        while IFS= read -r p; do
            [[ -n $p ]] || continue
            left=$(( left + 1 ))
            ui_dim "$(t import.excluded "${p#"$SRC"/}")"
        done < <(cd "$SRC" && find "$d" -path "$pat" -o -path "*/$pat" 2>/dev/null | head -n 20 | sed "s#^#$SRC/#")
    done
done
(( left == 0 )) || ui_info "$(t import.excluded_note)"
ui_ok "$(t import.done "$copied" "$skipped")"